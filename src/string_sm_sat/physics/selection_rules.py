"""S(U(1)^5) charge selection rules for the superpotential, with singlet insertions.

For V = (+)_{a=1..5} L_a the structure group S(U(1)^5) leaves an unbroken
U(1)^4 = U(1)^5 / U(1)_diag under which the low-energy fields carry the charges

    10_a        e_a                    from H^1(X, L_a)
    5bar_{ab}   e_a + e_b              from H^1(X, L_a (x) L_b)
    5_{ab}      -(e_a + e_b)           from H^1(X, L_a^* (x) L_b^*)
    S_{ab}      e_a - e_b              from H^1(X, L_a (x) L_b^*)

read as elements of Z^5 / Z(1,1,1,1,1).  A superpotential monomial is gauge
invariant exactly when its total charge is zero in that quotient, i.e. when the
sum in Z^5 equals m*(1,1,1,1,1) for some integer m.  Because every charge above
has an integer entry-sum, m is forced: m = (entry sum)/5, and the operator is
forbidden outright when that is not an integer.

Singlets acquire vacuum expectation values, so an operator that is not invariant
on its own can still be generated by inserting singlets.  The question

    "is there a monomial in the available S_{ab} whose charge cancels the
     residual charge of the operator?"

is exactly membership of a vector in the monoid generated by
{e_a - e_b : S_{ab} present}.  That monoid is the set of integer divergence
vectors of non-negative integer flows on the directed graph with an edge a -> b
for each available singlet, so membership is a network-flow feasibility
question: decidable exactly, and (the constraint matrix being totally
unimodular) a rational flow exists iff an integer one does.  The minimal number
of insertions is a min-cost flow with unit edge costs, which for infinite
capacities reduces to a transportation problem over all-pairs shortest paths.

Logical status.  Charge conservation is **necessary**, never sufficient:

* `FORBIDDEN_BY_SELECTION_RULE` is an EXACT statement that the coupling
  vanishes, to all orders in singlet insertions.  Nothing is truncated: the
  monoid membership test is exact and unbounded in the insertion order.
* `ALLOWED_AT_LEADING_ORDER` / `ALLOWED_WITH_SINGLET_INSERTIONS` say only that
  the charges permit the term.  Whether it is actually nonzero requires the
  Gamma-character rule and then the cohomological triple product; see
  `physics/yukawa.py`.

Reference: Anderson, Gray, Lukas, Palti arXiv:1202.1757 Sections 2 and 6;
Anderson, Constantin, Gray, Lukas, Palti arXiv:1307.4787 Section 6.
"""
from collections import Counter
from dataclasses import dataclass
from functools import lru_cache

from .constraints import Check, rule

RANK = 5
DIAGONAL = (1,) * RANK
INFINITY = float('inf')

SELECTION = rule(
    'u1_selection_rule', 'NECESSARY',
    '1202.1757 Sections 2,6; 1307.4787 Section 6',
    ('V a sum of five line bundles with c_1(V)=0; unbroken U(1)^4 = S(U(1)^5)/'
     'nothing further broken; singlet vacuum expectation values unconstrained in size; '
     'charge conservation is necessary, not sufficient, for a nonzero coupling',),
    False, False)


def unit(a):
    """e_a for a in 1..5."""
    return tuple(1 if i == a - 1 else 0 for i in range(RANK))


def add(*charges):
    return tuple(sum(values) for values in zip(*charges))


def ten(a):
    return unit(a)


def fivebar(a, b):
    return add(unit(a), unit(b))


def five(a, b):
    return tuple(-x for x in fivebar(a, b))


def singlet(a, b):
    return tuple(x - y for x, y in zip(unit(a), unit(b)))


def residual_charge(total):
    """The charge that singlet insertions must supply, or None if impossible.

    `total` must become m*(1,1,1,1,1); singlet charges have entry-sum zero, so m
    is determined by the entry-sum of `total` and must be an integer.
    """
    entry_sum = sum(total)
    if entry_sum % RANK:
        return None
    m = entry_sum // RANK
    return tuple(m - x for x in total)


def _shortest_paths(edges):
    """Unit-weight all-pairs shortest paths and the predecessor structure."""
    distance = [[INFINITY] * RANK for _ in range(RANK)]
    step = [[None] * RANK for _ in range(RANK)]
    for i in range(RANK):
        distance[i][i] = 0
    for a, b in edges:
        if 1 < distance[a - 1][b - 1]:
            distance[a - 1][b - 1] = 1
            step[a - 1][b - 1] = (a, b)
    for k in range(RANK):
        for i in range(RANK):
            for j in range(RANK):
                if distance[i][k] + distance[k][j] < distance[i][j]:
                    distance[i][j] = distance[i][k] + distance[k][j]
                    step[i][j] = step[i][k]
    return distance, step


def _path(step, i, j):
    """The edge sequence of a shortest path, as 1-based node pairs."""
    out = []
    while i != j:
        edge = step[i][j]
        if edge is None:
            return None
        out.append(edge)
        i = edge[1] - 1
    return out


def _transport(supplies, demands, cost):
    """Exact minimum-cost integer transportation plan, or None if infeasible.

    Sizes here are tiny (at most five sources and five sinks, small amounts), so
    the plan is found by exhaustive search with memoisation rather than by a
    general solver.  Total unimodularity guarantees the optimum is integral, so
    searching integer plans loses nothing.
    """
    sources = [i for i, s in enumerate(supplies) if s]
    sinks = tuple(i for i, d in enumerate(demands) if d)

    @lru_cache(maxsize=None)
    def best(index, remaining):
        if index == len(sources):
            return (0, ()) if not any(remaining) else None
        source = sources[index]
        amount = supplies[source]
        answer = None
        for split in _compositions(amount, len(sinks)):
            if any(x > y for x, y in zip(split, remaining)):
                continue
            price = 0
            for part, sink in zip(split, sinks):
                if not part:
                    continue
                if cost[source][sink] == INFINITY:
                    price = INFINITY
                    break
                price += part * cost[source][sink]
            if price == INFINITY:
                continue
            tail = best(index + 1, tuple(x - y for x, y in zip(remaining, split)))
            if tail is None:
                continue
            candidate = (price + tail[0], ((source, split),) + tail[1])
            if answer is None or candidate[0] < answer[0]:
                answer = candidate
        return answer

    result = best(0, tuple(demands[i] for i in sinks))
    if result is None:
        return None
    plan = {}
    for source, split in result[1]:
        for part, sink in zip(split, sinks):
            if part:
                plan[(source, sink)] = part
    return result[0], plan


@lru_cache(maxsize=None)
def _compositions(total, parts):
    if parts == 1:
        return ((total,),)
    out = []
    for first in range(total + 1):
        for rest in _compositions(total - first, parts - 1):
            out.append((first,) + rest)
    return tuple(out)


def monoid_membership(target, available):
    """Express `target` as a non-negative integer combination of singlet charges.

    `available` is an iterable of ordered pairs (a, b) for the singlets S_{ab}
    present in the spectrum.  Returns (feasible, insertions, monomial) where
    `insertions` is the minimum total number of singlet factors and `monomial`
    is a Counter over (a, b).
    """
    edges = tuple(sorted({(a, b) for a, b in available if a != b}))
    if not any(target):
        return True, 0, Counter()
    if sum(target):
        return False, None, None
    distance, step = _shortest_paths(edges)
    supplies = [max(x, 0) for x in target]
    demands = [max(-x, 0) for x in target]
    outcome = _transport(supplies, demands, distance)
    if outcome is None:
        return False, None, None
    cost, plan = outcome
    monomial = Counter()
    for (source, sink), amount in plan.items():
        path = _path(step, source, sink)
        for edge in path:
            monomial[edge] += amount
    return True, int(cost), monomial


@dataclass(frozen=True)
class Selection:
    charge: tuple
    status: str
    insertions: int | None = None
    monomial: tuple = ()

    @property
    def allowed(self):
        return self.status != 'FORBIDDEN_BY_SELECTION_RULE'

    def as_dict(self):
        return {'charge': list(self.charge), 'status': self.status,
                'insertions': self.insertions,
                'monomial': [[list(edge), count] for edge, count in self.monomial]}


def classify(charges, singlets):
    """Classify an operator by U(1)^4 charge conservation with singlet insertions."""
    total = add(*charges) if charges else (0,) * RANK
    residual = residual_charge(total)
    if residual is None:
        return Selection(total, 'FORBIDDEN_BY_SELECTION_RULE')
    feasible, insertions, monomial = monoid_membership(residual, singlets)
    if not feasible:
        return Selection(total, 'FORBIDDEN_BY_SELECTION_RULE')
    status = ('ALLOWED_AT_LEADING_ORDER' if insertions == 0
              else 'ALLOWED_WITH_SINGLET_INSERTIONS')
    return Selection(total, status, insertions,
                     tuple(sorted(monomial.items())) if monomial else ())


def check(charges, singlets):
    selection = classify(charges, singlets)
    return Check(SELECTION, 'PASS' if selection.allowed else 'FAIL',
                 selection.insertions, selection.as_dict())


def _lower_bound(residual, distance):
    """Minimum insertions still needed, from the transportation relaxation."""
    supplies = [max(x, 0) for x in residual]
    demands = [max(-x, 0) for x in residual]
    if not any(supplies):
        return 0
    outcome = _transport(supplies, demands, distance)
    return INFINITY if outcome is None else outcome[0]


def enumerate_monomials(residual, available, max_order):
    """Every singlet monomial of total degree <= max_order with the given charge.

    Exhaustive, with the min-cost-flow value as an admissible lower bound for
    pruning, so the enumeration is complete for the stated order and no monomial
    is missed.  Monomials that differ by a charge-neutral factor are all listed
    separately, matching the published convention.
    """
    edges = tuple(sorted({(a, b) for a, b in available if a != b}))
    distance, _ = _shortest_paths(edges)
    found = []

    def descend(index, remaining, budget, chosen):
        if not any(remaining):
            found.append(frozenset(Counter(chosen).items()))
            # do not stop: a valid monomial times a charge-neutral monomial is
            # again valid, and the published tables list those too
        if index == len(edges) or budget == 0:
            return
        if _lower_bound(remaining, distance) > budget:
            return
        edge = edges[index]
        charge = singlet(*edge)
        descend(index + 1, remaining, budget, chosen)
        current = remaining
        for count in range(1, budget + 1):
            current = tuple(x - y for x, y in zip(current, charge))
            descend(index + 1, current, budget - count, chosen + (edge,) * count)

    descend(0, tuple(residual), max_order, ())
    return set(found)
